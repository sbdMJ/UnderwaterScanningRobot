"""Aggregate per-cell metrics into the paper tables: mean +- SD with per-trial values kept.

Reads every ``metrics_<method>_<cond>_s<seed>.json`` under one experiment's results
directory, flattens nested keys to dotted paths (``mpc.solve_ms_mean``), groups by
(method, condition) and reports mean, SD and the individual per-trial values — the
statistics format experiments_plan.md mandates (no min/max bars). Tuning ``budget.json``
files are folded in the same way for the E4(b) cost table.

Pure stdlib + numpy: runs on the dev PC, the sim host, or CI without extras.
"""
from __future__ import annotations

import csv
import json
import re
from pathlib import Path

import numpy as np

_METRICS_RE = re.compile(r"^metrics_(?P<method>[^_]+)_(?P<cond>.+)_s(?P<seed>\d+)\.json$")


def flatten(d: dict, prefix: str = "") -> dict:
    """Nested dict -> {dotted.path: leaf}; lists are kept as-is (not indexed)."""
    out: dict = {}
    for k, v in d.items():
        key = f"{prefix}{k}"
        if isinstance(v, dict):
            out.update(flatten(v, f"{key}."))
        else:
            out[key] = v
    return out


def collect(results_dir: str) -> list[dict]:
    """One flat row per metrics json, tagged with method/cond/seed parsed from the name.

    Accepts either the experiment dir (descends into its ``metrics/`` subdirectory) or
    a directory that holds the json files directly (legacy/flat layouts).
    """
    d = Path(results_dir)
    if (d / "metrics").is_dir():
        d = d / "metrics"
    rows = []
    for path in sorted(d.glob("metrics_*.json")):
        m = _METRICS_RE.match(path.name)
        if m is None:
            continue
        with open(path) as fh:
            row = flatten(json.load(fh))
        row["method"], row["cond"], row["seed"] = m["method"], m["cond"], int(m["seed"])
        rows.append(row)
    return rows


def summarize(rows: list[dict], metrics: list[str]) -> dict[tuple[str, str], dict]:
    """(method, cond) -> {metric: {"mean", "sd", "values"}} over seeds (trials)."""
    groups: dict[tuple[str, str], list[dict]] = {}
    for row in rows:
        groups.setdefault((row["method"], row["cond"]), []).append(row)
    out = {}
    for key, grp in sorted(groups.items()):
        entry = {"n_trials": len(grp)}
        for metric in metrics:
            values = [float(r[metric]) for r in grp if metric in r and _is_number(r[metric])]
            entry[metric] = {
                "mean": float(np.mean(values)) if values else float("nan"),
                "sd": float(np.std(values, ddof=1)) if len(values) > 1 else 0.0,
                "values": values,
            }
        out[key] = entry
    return out


def _is_number(v) -> bool:
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def write_table_csv(summary: dict, metrics: list[str], path: str) -> None:
    """Long-format csv: one row per (method, cond, metric) with mean/sd/per-trial values."""
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["method", "cond", "metric", "mean", "sd", "n_trials", "values"])
        for (method, cond), entry in summary.items():
            for metric in metrics:
                s = entry[metric]
                w.writerow([method, cond, metric, f"{s['mean']:.6g}", f"{s['sd']:.6g}",
                            entry["n_trials"], ";".join(f"{v:.6g}" for v in s["values"])])


METHOD_ORDER = ("nominal", "bo", "ppo", "ssi", "diff")
METHOD_LABELS = {"nominal": "Nominal NMPC", "bo": "BO-tuned NMPC", "ppo": "PPO",
                 "ssi": "SSI-MPC", "diff": "Diff-WMPC (ours)"}


def _method_key(method: str) -> int:
    return METHOD_ORDER.index(method) if method in METHOD_ORDER else len(METHOD_ORDER)


def _tex_escape(s: str) -> str:
    return s.replace("_", "\\_")


def _cell(stat: dict, fmt: str = "{:.3g}") -> str:
    mean, sd = stat["mean"], stat["sd"]
    if not np.isfinite(mean):
        return "--"
    return f"{fmt.format(mean)} $\\pm$ {fmt.format(sd)}"


def write_table_tex(summary: dict, metrics: list[str], path: str, *,
                    labels: dict[str, str] | None = None, fmt: str = "{:.3g}") -> None:
    """Paper-ready booktabs table: one row per method, one block per condition.

    Cells are ``mean $\\pm$ sd`` over trials (per-trial values live in the csv; the
    scatter overlay figure is generated separately). Non-finite means (e.g. an inf
    objective from a collided trial) render as ``--``.
    """
    labels = labels or {}
    conds = sorted({cond for (_m, cond) in summary})
    heads = [labels.get(m, _tex_escape(m)) for m in metrics]
    lines = [
        "% Auto-generated by marinelab.experiments.aggregate - do not edit by hand.",
        f"\\begin{{tabular}}{{l{'c' * len(metrics)}}}",
        "\\toprule",
        "Method & " + " & ".join(heads) + " \\\\",
    ]
    for cond in conds:
        rows = sorted(((m, c) for (m, c) in summary if c == cond),
                      key=lambda mc: _method_key(mc[0]))
        lines.append("\\midrule")
        if len(conds) > 1:
            lines.append(f"\\multicolumn{{{len(metrics) + 1}}}{{l}}"
                         f"{{\\textit{{{_tex_escape(cond)}}}}} \\\\")
        for method, c in rows:
            entry = summary[(method, c)]
            cells = " & ".join(_cell(entry[metric], fmt) for metric in metrics)
            lines.append(f"{METHOD_LABELS.get(method, _tex_escape(method))} & {cells} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text("\n".join(lines) + "\n", encoding="utf-8")


def collect_budgets(tuning_root: str) -> dict[str, dict]:
    """method -> budget.json content, for the E4(b) tuning-cost column."""
    out = {}
    for path in sorted(Path(tuning_root).glob("*/budget.json")):
        with open(path) as fh:
            out[path.parent.name] = json.load(fh)
    return out
